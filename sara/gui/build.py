"""
sara/gui/build.py -- bundles the GUI sources into two files.

Sources live in feature folders (js/<group>/, style/<group>/); assets.json is
the ONE place that says which files load and in what order. index.html links
only bundle/app.css and bundle/app.js, so startup is two requests instead of
~76 and nobody has to keep 78 <link>/<script> tags in order by hand.

    python -m sara.gui.build           rebuild bundle/
    python -m sara.gui.build --check   exit 1 if bundle/ is stale (CI / tests)

bootstrap.py calls ensure_built() before the window opens, so editing a
source file is picked up on the next launch. The bundle is committed so a
fresh clone runs without a build step; tests/test_gui_assets.py fails if it
is out of date.

Concatenation keeps behaviour identical to separate classic <script> tags
(they share one global scope either way). Each file is separated by ";" so a
file that does not end in a semicolon cannot merge with the next one.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

GUI_DIR = Path(__file__).resolve().parent
MANIFEST = GUI_DIR / "assets.json"
BUNDLE_DIR = GUI_DIR / "bundle"
OUTPUTS = {"css": BUNDLE_DIR / "app.css", "js": BUNDLE_DIR / "app.js"}
INDEX_HTML = GUI_DIR / "index.html"


def load_manifest() -> dict[str, list[str]]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _read(rel: str) -> str:
    return (GUI_DIR / rel).read_text(encoding="utf-8").replace("\r\n", "\n")


def render(kind: str, manifest: dict[str, list[str]] | None = None) -> str:
    files = (manifest or load_manifest())[kind]
    sep = "\n;\n" if kind == "js" else "\n"
    parts = [
        f"/* GENERATED by sara/gui/build.py from assets.json -- do not edit. */\n"
    ]
    for rel in files:
        parts.append(f"/* ==== {rel} ==== */\n{_read(rel).rstrip()}\n")
    return sep.join(parts)


def _version(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def _index_with_versions(html: str, versions: dict[str, str]) -> str:
    """Point index.html at bundle/app.css?v=<hash> / app.js?v=<hash>.

    WebView2 keeps a file it fetched earlier without asking again for a while (heuristic caching),
    so after an update the app ran the OLD bundle. A new URL for every new content avoids that."""
    for name, ver in versions.items():
        html = re.sub(r"bundle/" + re.escape(name) + r"(\?v=[0-9a-f]+)?", f"bundle/{name}?v={ver}", html)
    return html


def _wanted_index(rendered: dict[str, str]) -> str:
    versions = {OUTPUTS[k].name: _version(v) for k, v in rendered.items()}
    return _index_with_versions(INDEX_HTML.read_text(encoding="utf-8"), versions)


def is_stale() -> list[str]:
    """Names of bundle files that are missing or differ from the sources."""
    manifest = load_manifest()
    stale = []
    rendered = {}
    for kind, out in OUTPUTS.items():
        want = rendered[kind] = render(kind, manifest)
        if not out.exists() or out.read_text(encoding="utf-8") != want:
            stale.append(out.name)
    if INDEX_HTML.read_text(encoding="utf-8") != _wanted_index(rendered):
        stale.append(INDEX_HTML.name)
    return stale


def build() -> list[str]:
    """Write the bundle; returns the files that changed."""
    manifest = load_manifest()
    BUNDLE_DIR.mkdir(exist_ok=True)
    changed = []
    rendered = {}
    for kind, out in OUTPUTS.items():
        want = rendered[kind] = render(kind, manifest)
        if not out.exists() or out.read_text(encoding="utf-8") != want:
            out.write_text(want, encoding="utf-8", newline="\n")
            changed.append(out.name)
    html = INDEX_HTML.read_text(encoding="utf-8")
    new_html = _wanted_index(rendered)
    if new_html != html:
        INDEX_HTML.write_text(new_html, encoding="utf-8", newline="\n")
        changed.append(INDEX_HTML.name)
    return changed


def _clear_webview_http_cache() -> None:
    """Delete WebView2's HTTP cache (not cookies / localStorage) so the page itself is fetched again.

    The bundle URLs carry a content hash, but index.html is the page the window navigates to and
    WebView2 may serve its cached copy for a while. Run before the window exists."""
    import os
    import shutil

    root = Path(os.environ.get("APPDATA", "")) / "pywebview" / "EBWebView" / "Default"
    for sub in ("Cache", "Code Cache"):
        shutil.rmtree(root / sub, ignore_errors=True)


def ensure_built() -> None:
    """Called at app start. Never raises: a stale bundle still runs."""
    try:
        build()
        # Remember which GUI version the window last loaded; a different one => drop the HTTP cache once.
        current = _version(INDEX_HTML.read_text(encoding="utf-8"))
        # The stamp lives next to the user's WebView2 profile, not in the repo.
        import os

        marker = Path(os.environ.get("APPDATA", "")) / "pywebview" / "sara_gui_version.txt"
        if not marker.exists() or marker.read_text(encoding="utf-8").strip() != current:
            _clear_webview_http_cache()
            marker.parent.mkdir(parents=True, exist_ok=True)
            marker.write_text(current, encoding="utf-8")
    except Exception as e:  # read-only install, missing source, ...
        print(f"[GUI] bundle rebuild skipped: {e}")


if __name__ == "__main__":
    if "--check" in sys.argv:
        stale = is_stale()
        if stale:
            print(f"GUI bundle is stale: {', '.join(stale)} (run: python -m sara.gui.build)")
            sys.exit(1)
        print("GUI bundle is up to date.")
    else:
        done = build()
        print("rebuilt: " + (", ".join(done) if done else "nothing to do (already up to date)"))
