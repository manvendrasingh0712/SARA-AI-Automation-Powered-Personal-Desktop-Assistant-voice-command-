"""Keep `.env.example` complete: every `os.getenv("KEY", ...)` the code reads must appear in it (active or commented).

    python scripts/gen_env_example.py            # rewrite the AUTO-GENERATED block of .env.example
    python scripts/gen_env_example.py --check    # exit 1 and list the undocumented keys (used by tests/test_env_example.py)

Hand-written lines above the block are never touched. For each undocumented key the block gets one commented line with
the default, the type (from the _int/_float/_bool wrapper) and the comment that sits right above it in the source.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / ".env.example"
BEGIN = "# >>> AUTO-GENERATED by scripts/gen_env_example.py (keys the code reads that are not described above) >>>"
END = "# <<< END AUTO-GENERATED <<<"
# Keys that are not settings (OS / debugging variables the code merely reads).
IGNORE = {"APPDATA", "LOCALAPPDATA", "PATH", "PROGRAMFILES", "PROGRAMW6432", "USERNAME", "USERPROFILE", "TEMP", "TMP"}

PROFILES = """\
# ── Profiles (copy one block into .env) ─────────────────────────────────────────────────────────────────────────────
# offline-first (default on a 4 GB GPU): local model, nothing leaves the PC
#   LLM_BACKEND=ollama          KOKORO_USE_GPU=False       WHISPER_MAIN_DEVICE=cpu       ROUTER_MODE=shadow
# cloud-fast: Gemini answers, Ollama is the offline fallback
#   LLM_BACKEND=gemini          LLM_FALLBACK_ENABLED=true  ROUTER_MODE=on                GEMINI_MAX_OUTPUT_TOKENS=400
# low-latency-gpu: cloud LLM frees the GPU for speech (measure before keeping)
#   LLM_BACKEND=gemini          KOKORO_USE_GPU=True        WHISPER_MAIN_DEVICE=cuda      OLLAMA_KEEP_ALIVE=5m
"""


def source_files():
    files = [ROOT / "config.py", ROOT / "main.py", ROOT / "ollama_manager.py", ROOT / "logging_config.py"]
    files += sorted((ROOT / "sara").rglob("*.py"))
    return [p for p in files if p.exists()]


def find_keys() -> dict:
    """KEY -> (default text, type, comment)."""
    keys: dict = {}
    for path in source_files():
        text = path.read_text(encoding="utf-8", errors="ignore")
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        lines = text.splitlines()
        parents = {}
        for node in ast.walk(tree):
            for ch in ast.iter_child_nodes(node):
                parents[ch] = node
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "getenv"):
                continue
            if not node.args or not isinstance(node.args[0], ast.Constant) or not isinstance(node.args[0].value, str):
                continue
            key = node.args[0].value
            if key in IGNORE or not re.fullmatch(r"[A-Z][A-Z0-9_]+", key):
                continue
            default, typ = "", "str"
            if len(node.args) > 1:
                default = ast.unparse(node.args[1]).strip("'\"")
            wrapper = parents.get(node)
            if isinstance(wrapper, ast.Call) and isinstance(wrapper.func, ast.Name):
                typ = {"_int": "int", "_float": "float", "_bool": "bool"}.get(wrapper.func.id, typ)
                for kw in wrapper.keywords:
                    if kw.arg == "default":
                        default = ast.unparse(kw.value).strip("'\"")
            comment = ""
            i = node.lineno - 2
            while i >= 0 and lines[i].strip().startswith("#"):
                comment = lines[i].strip().lstrip("# ").strip() + (" " + comment if comment else "")
                i -= 1
            if key not in keys or (comment and not keys[key][2]):
                keys[key] = (default, typ, comment)
    return keys


def documented_keys(text: str) -> set:
    return set(re.findall(r"^[#\s]*([A-Z][A-Z0-9_]+)\s*=", text, re.MULTILINE))


def split_example(text: str):
    if BEGIN in text:
        head = text.split(BEGIN)[0].rstrip() + "\n"
    else:
        head = text.rstrip() + "\n"
    return head


def render(keys: dict, documented: set) -> str:
    out = [BEGIN]
    for key in sorted(k for k in keys if k not in documented):
        default, typ, comment = keys[key]
        desc = f" {comment[:110]}" if comment else ""
        out.append(f"# {key}={default}".ljust(46) + f"# ({typ}){desc}")
    out.append(END)
    return "\n".join(out) + "\n"


def undocumented(keys: dict | None = None) -> list:
    keys = keys or find_keys()
    return sorted(k for k in keys if k not in documented_keys(EXAMPLE.read_text(encoding="utf-8")))


def main(argv) -> int:
    keys = find_keys()
    text = EXAMPLE.read_text(encoding="utf-8")
    if "--check" in argv:
        missing = undocumented(keys)
        for k in missing:
            print(f".env.example does not mention {k}")
        print(f"{len(keys)} keys read by the code, {len(missing)} undocumented")
        return 1 if missing else 0
    head = split_example(text)
    documented = documented_keys(head)
    if "Profiles (copy one block" not in head:
        head = head.rstrip() + "\n\n" + PROFILES
    EXAMPLE.write_text(head + "\n" + render(keys, documented), encoding="utf-8", newline="")
    print(f"{len(keys)} keys read by the code, {len([k for k in keys if k not in documented])} added to the auto block")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
